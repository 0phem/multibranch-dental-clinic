import assert from 'node:assert/strict'

// Synthetic Owner harness with real Leaflet interactions and mocked persistence API.
export async function runOwnerBranchAcceptance(page, base = 'http://127.0.0.1:5176') {
  const patches = []
  await page.route('**/tile.openstreetmap.org/**', route => route.abort())
  await page.route('**/sanctum/csrf-cookie', route => route.fulfill({status:204}))
  await page.route('**/api/**', async route => {
    const request = route.request()
    const path = new URL(request.url()).pathname
    if (request.method() === 'PATCH' && path.startsWith('/api/branches/')) {
      const payload = request.postDataJSON()
      patches.push(payload)
      const id = path.split('/').at(-1)
      await route.fulfill({status:200, contentType:'application/json', body:JSON.stringify({data:{id,...payload}})})
    } else if (path === '/api/branch-services') {
      const payload = request.postDataJSON()
      await route.fulfill({status:200,contentType:'application/json',body:JSON.stringify({data:payload})})
    } else await route.fulfill({status:200,contentType:'application/json',body:'{"data":[]}'} )
  })
  const results = []
  for (const width of [1440, 390]) {
    patches.length = 0
    await page.setViewportSize({width,height:1000})
    await page.goto(`${base}/tests/fixtures/owner-branches.html`)
    const code = page.getByLabel('Branch code', {exact:true})
    await code.waitFor()
    const contrast = await page.locator('.branch-overview-card .status, .branch-code-badge').evaluateAll(elements => elements.map(el => {
      const rgb = value => value.match(/[\d.]+/g).slice(0, 3).map(Number)
      const luminance = values => values.map(c => {const n=c/255;return n<=.04045?n/12.92:((n+.055)/1.055)**2.4}).reduce((s,c,i)=>s+c*[.2126,.7152,.0722][i],0)
      const style = getComputedStyle(el), a = luminance(rgb(style.color)), b = luminance(rgb(style.backgroundColor))
      return (Math.max(a,b)+.05)/(Math.min(a,b)+.05)
    }))
    assert.ok(contrast.every(value => value >= 4.5), 'branch-code and status text have readable contrast')
    assert.equal(await code.locator('option[value="BRC-B"]').evaluate(el => el.disabled), true, 'duplicate code cannot be selected')
    await code.selectOption('BRC-D')
    const map = page.locator('.branch-map-canvas')
    await map.locator('.leaflet-control-zoom-in').waitFor()
    assert.equal(await map.locator('.leaflet-marker-icon').count(), 0, 'no placeholder location is presented as a saved pin')
    const mapId = await map.evaluate(el => el._leaflet_id)
    await map.locator('.leaflet-control-zoom-in').click()
    const rect = await map.boundingBox()
    await page.mouse.click(rect.x + rect.width * .6, rect.y + rect.height * .55)
    const marker = map.locator('.leaflet-marker-icon')
    await marker.waitFor()
    const graphic = await marker.locator('svg').boundingBox()
    const positionedMap = await map.boundingBox()
    assert.ok(Math.abs(graphic.x + graphic.width / 2 - (positionedMap.x + rect.width * .6)) < 2 && Math.abs(graphic.y + graphic.height - (positionedMap.y + rect.height * .55)) < 2, 'visual pin tip identifies the clicked coordinate')
    await marker.evaluate(el => { el.dataset.acceptancePin = 'same-pin' })
    const firstCoords = await page.locator('.coord-value').allTextContents()
    const pin = await marker.boundingBox()
    await page.mouse.move(pin.x + pin.width / 2, pin.y + pin.height / 2)
    await page.mouse.down()
    await page.mouse.move(pin.x + pin.width / 2 + 35, pin.y + pin.height / 2 + 20, {steps:8})
    await page.mouse.up()
    await page.waitForTimeout(150)
    const dragged = await page.locator('.coord-value').allTextContents()
    assert.ok(firstCoords.join() !== dragged.join(), 'dragging updates coordinate readout')
    assert.equal(await map.evaluate(el => el._leaflet_id), mapId, 'pin updates retain the same Leaflet map')
    assert.equal(await marker.getAttribute('data-acceptance-pin'), 'same-pin', 'pin updates do not recreate marker')
    assert.equal(patches.length, 0, 'starting viewport and pin changes are never persisted without Publish')
    await page.getByRole('button', {name:'Publish Branch Changes'}).click()
    await page.getByRole('status').filter({hasText:'Branch configuration saved.'}).waitFor()
    assert.equal(patches.at(-1).branch_code, 'BRC-D')
    assert.equal(Number(dragged[0]), patches.at(-1).latitude)
    assert.equal(Number(dragged[1]), patches.at(-1).longitude)
    // Unmount and reopen the map from the saved canonical branch response.
    await page.getByRole('button', {name:'Opening Hours',exact:true}).click()
    const monday = page.getByRole('button', {name:'Monday: Open',exact:true})
    await monday.click()
    assert.equal(await page.getByRole('button', {name:'Monday: Closed',exact:true}).getAttribute('aria-pressed'), 'true')
    assert.equal(await page.getByRole('button', {name:'Tuesday: Open',exact:true}).isDisabled(), true, 'last operating day cannot be closed')
    await page.getByRole('button', {name:'Publish Branch Changes'}).click()
    await page.waitForTimeout(100)
    assert.equal(patches.at(-1).weekly_hours['1'], undefined)
    assert.equal(patches.at(-1).weekly_hours['2'].open, '08:00')
    assert.equal(patches.at(-1).status, 'Open', 'weekday closure does not close the branch operationally')
    await page.getByRole('button', {name:'Details & Contact',exact:true}).click()
    await map.locator('.leaflet-marker-icon').waitFor()
    assert.equal(await code.inputValue(), 'BRC-D')
    assert.equal((await page.locator('.coord-value').allTextContents()).join(), dragged.join(), 'saved location reopens unchanged')
    const second = page.locator('.branch-overview-card').nth(1).getByRole('button')
    await second.focus(); await page.keyboard.press('Enter')
    await page.waitForFunction(() => [...document.querySelectorAll('.coord-value')].every(el => el.textContent === 'Not pinned'))
    assert.equal(await map.locator('.leaflet-marker-icon').count(), 0, 'unpinned branch does not inherit another location')
    const original = page.locator('.branch-overview-card').first().getByRole('button')
    await original.focus(); await page.keyboard.press('Enter')
    await map.locator('.leaflet-marker-icon').waitFor()
    assert.equal((await page.locator('.coord-value').allTextContents()).join(), dragged.join(), 'keyboard branch selection restores saved location')
    await page.getByRole('button', {name:/^Services \(/}).click()
    const cells = page.locator('.branch-service-item')
    assert.equal(await cells.count(), 4)
    const boxes = await cells.evaluateAll(elements => elements.map(el => { const r=el.getBoundingClientRect(); return {x:r.x,y:r.y} }))
    if (width === 1440) {
      assert.equal(boxes[0].y, boxes[1].y)
      assert.ok(boxes[2].y > boxes[0].y)
      assert.equal(boxes[0].x, boxes[2].x)
    } else assert.ok(boxes.every(box => box.x === boxes[0].x), 'phone services are one column')
    await cells.first().locator('input').click()
    await page.waitForFunction(() => document.querySelector('.branch-service-item input').checked)
    assert.equal(await cells.first().locator('input').isChecked(), true)
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'no page horizontal overflow')
    results.push(`Owner ${width}: code selection, real Leaflet click/drag/lifecycle, saved coordinate round trip, weekday closure, disabled last day, services layout/toggle`)
  }
  return results
}
