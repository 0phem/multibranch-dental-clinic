import assert from 'node:assert/strict'
import {pathToFileURL} from 'node:url'
import {mkdir} from 'node:fs/promises'
// Usage: node tests/staff-workflow-a8-rendered.mjs <path-to-playwright/index.mjs>
const {chromium}=await import(process.argv[2]?pathToFileURL(process.argv[2]).href:'playwright')
const browser=await chromium.launch({headless:true,channel:'chrome'})
await mkdir('docs/ui-review/staff-a8',{recursive:true})
try {
 for(const width of [1440,390]) {
  const page=await browser.newPage({viewport:{width,height:1000}})
  const errors=[];page.on('pageerror',e=>errors.push(e.message))
  await page.route('**/api/**',r=>{
   const u=new URL(r.request().url())
   if(u.pathname.endsWith('/availability'))return r.fulfill({json:{data:{date:'2026-10-29',slots:[{date:'2026-10-29',start_time:'14:00',end_time:'14:30'}]}}})
   return r.fulfill({json:{data:{id:'01SYNTHETICPATIENTPUBLIC001',name:'Synthetic Selected Patient',profile_access:'identity'}}})
  })
  await page.goto('http://127.0.0.1:5178/tests/fixtures/staff-workflow-a8.html')
  await page.getByRole('button',{name:'Open Patient Record',exact:true}).focus()
  await page.keyboard.press('Enter')
  await page.locator('.patient-record-head h2').waitFor()
  assert.equal(await page.locator('.patient-record-head h2').innerText(),'Synthetic Selected Patient')
  await page.getByRole('button',{name:'Book Appointment',exact:true}).click()
  const dialog=page.getByRole('dialog')
  assert.equal(await dialog.getByRole('textbox',{name:'Patient',exact:true}).inputValue(),'Synthetic Selected Patient')
  assert.deepEqual(await dialog.getByRole('combobox',{name:'Branch',exact:true}).locator('option').allTextContents(),['Synthetic branch'])
  assert.equal(await dialog.getByRole('combobox',{name:'Service',exact:true}).inputValue(),'')
  assert.equal(await dialog.getByRole('combobox',{name:/^Dentist/}).inputValue(),'')
  const confirm=dialog.getByRole('button',{name:'Confirm appointment',exact:true})
  assert.equal(await confirm.isDisabled(),true)
  await dialog.getByRole('combobox',{name:'Service',exact:true}).selectOption('s2')
  await dialog.getByRole('button',{name:'2:00 PM',exact:true}).click()
  assert.equal(await confirm.isDisabled(),true,'restricted confirmation required')
  await dialog.getByRole('checkbox').check()
  await page.evaluate(()=>{window.bookingFailure='conflict'})
  await confirm.click();await dialog.getByText('Availability changed',{exact:true}).waitFor()
  const failedKey=await page.evaluate(()=>window.lastBooking.options.key)
  await page.evaluate(()=>{window.bookingFailure='validation'})
  await confirm.click();await dialog.getByText('This slot can’t be booked',{exact:true}).waitFor()
  assert.notEqual(await page.evaluate(()=>window.lastBooking.options.key),failedKey)
  await page.evaluate(()=>{window.bookingFailure=null})
  await page.screenshot({path:`docs/ui-review/staff-a8/booking-${width}.png`,fullPage:true})
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'mobile overflow')
  await confirm.click();await dialog.waitFor({state:'hidden'})
  const booking=await page.evaluate(()=>window.lastBooking)
  assert.equal(booking.payload.patientPublicId,'01SYNTHETICPATIENTPUBLIC001')
  assert.equal(booking.payload.branchId,'b1');assert.equal(booking.payload.dentistId,null)
  assert.equal(booking.payload.consultationAcknowledged,true)
  await page.getByText('Appointment confirmed.',{exact:true}).waitFor()
  await page.screenshot({path:`docs/ui-review/staff-a8/record-${width}.png`,fullPage:true})
  // Exercise existing reschedule and follow-up contracts through the same form.
  await page.evaluate(()=>window.fixture.navigate('form',{appointment:window.fixture.state.appointments[0]}))
  assert.equal(await page.getByRole('combobox',{name:'Service',exact:true}).isDisabled(),true)
  await page.getByRole('button',{name:'2:00 PM',exact:true}).click()
  await page.getByRole('button',{name:'Confirm appointment',exact:true}).click()
  assert.equal(await page.evaluate(()=>window.lastReschedule.a.id),'appt1')
  await page.evaluate(()=>window.fixture.navigate('appointments'))
  await page.evaluate(()=>window.fixture.navigate('form',{followup:{patientId:'01SYNTHETICPATIENTPUBLIC001',branchId:'b1',dentistId:'d1'}}))
  assert.equal(await page.getByRole('textbox',{name:'Patient',exact:true}).inputValue(),'Synthetic Selected Patient')
  assert.equal(await page.getByRole('combobox',{name:/^Dentist/}).isDisabled(),true)
  await page.evaluate(()=>window.fixture.navigate('appointments'))
  await page.evaluate(()=>window.fixture.navigate('form',{followup:{patientId:'missing',branchId:'b1',dentistId:'d1'}}))
  await page.getByText(/no clinic account record on the server/).waitFor()
  assert.equal(await page.getByRole('button',{name:'Confirm appointment',exact:true}).count(),0)
  await page.evaluate(()=>window.fixture.navigate('appointments'))
  await page.evaluate(()=>window.fixture.navigate('form',{prefill:{patientPublicId:'01SYNTHETICPATIENTPUBLIC001',patientName:'Synthetic Selected Patient',branchId:'b2',serviceId:'s1'}}))
  assert.equal(await page.getByRole('button',{name:'Confirm appointment',exact:true}).isDisabled(),true,'unauthorized prefill branch cannot submit')
  // The new row shortcut fails closed for identity mismatch, inaccessible branch, legacy or unresolved Patient.
  const guards=await page.evaluate(async()=>{
   const {appointmentRecordPatient}=await import('/src/pages/Scheduling.jsx')
   const {state,store}=window.fixture,a=state.appointments[0],session=store.session
   return [!!appointmentRecordPatient(a,state,session),appointmentRecordPatient({...a,patientPublicId:'wrong'},state,session),appointmentRecordPatient({...a,branchId:'b2'},state,session),appointmentRecordPatient({...a,patientId:'missing'},state,session),appointmentRecordPatient(a,state,{...session,role:'owner'})]
  })
  assert.deepEqual(guards,[true,null,null,null,null])
  await page.evaluate(()=>{window.fixture.state.patients[0].serverProjection=false;window.fixture.navigate('appointments')})
  assert.equal(await page.getByRole('button',{name:'Open Patient Record',exact:true}).count(),0)
  await page.evaluate(()=>{window.fixture.store.session.serverUserId=null;window.fixture.navigate('patients',{patientId:'01SYNTHETICPATIENTPUBLIC001'})})
  assert.equal(await page.getByRole('button',{name:'Book Appointment',exact:true}).isDisabled(),true)
  await page.getByText(/no verified clinic server identity/).waitFor()
  assert.deepEqual(errors,[])
  console.log(`PASS ${width}: A 2→1 clicks; B 3→1 activations; exact identity, branch guard, required fields, restricted confirmation, conflict/validation/success, reschedule/follow-up, keyboard, overflow`)
  await page.close()
 }
} finally {await browser.close()}
